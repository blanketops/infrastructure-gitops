#!/usr/bin/env bash
# Export the trust a SupplyChainPolicy rendered on the build engine into the
# read engine: the public trust anchors (blanketops-sigstore-roots), the
# policy-controller TrustRoot and the ClusterImagePolicies. Run it against the
# build cluster, review the diff, commit; Argo CD applies it to the read cluster.
#
# usage: hack/export-trust.sh [-c build-context] [-n namespace]
#   -c  kubeconfig context of the build cluster (default: current context)
#   -n  namespace of the SupplyChainPolicies and the roots ConfigMap (default: default)
set -euo pipefail

context=""
namespace="default"
while getopts "c:n:" opt; do
  case $opt in
    c) context=$OPTARG ;;
    n) namespace=$OPTARG ;;
    *) echo "usage: $0 [-c build-context] [-n namespace]" >&2; exit 2 ;;
  esac
done

for tool in kubectl jq base64 sha256sum; do
  command -v "$tool" >/dev/null || { echo "$tool is required" >&2; exit 1; }
done

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/platforms/secure-read-engine/trust"
kc=(kubectl)
[[ -n $context ]] && kc+=(--context "$context")

# Pre-flight: export only what every policy has finished rendering. Fails when
# the namespace has no SupplyChainPolicy at all.
"${kc[@]}" -n "$namespace" wait supplychainpolicies.supplychain.blanketops.dev \
  --all --for=condition=Ready --timeout=2m

strip='del(.metadata.uid, .metadata.resourceVersion, .metadata.creationTimestamp,
  .metadata.generation, .metadata.managedFields, .metadata.ownerReferences,
  .metadata.annotations, .status)'

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The public trust anchors, as a readable, reviewable record in Git. The
# TrustRoot below embeds the same keys and is what policy-controller enforces.
"${kc[@]}" -n "$namespace" get configmap blanketops-sigstore-roots -o json |
  jq '{apiVersion, kind, metadata: {name: .metadata.name, namespace: "cosign-system"}, data}' \
  > "$tmp/configmap-roots.json"

# Everything the operator rendered for this namespace's policies.
"${kc[@]}" get trustroots.policy.sigstore.dev,clusterimagepolicies.policy.sigstore.dev \
  -l "blanketops.dev/managed=true,blanketops.dev/supply-chain-policy-namespace=$namespace" \
  -o json > "$tmp/rendered.json"

count=$(jq '.items | length' "$tmp/rendered.json")
if [[ $count -eq 0 ]]; then
  echo "no rendered TrustRoot or ClusterImagePolicy found for namespace $namespace" >&2
  exit 1
fi

files=(configmap-roots.json)
for i in $(seq 0 $((count - 1))); do
  item=$(jq -c ".items[$i] | $strip" "$tmp/rendered.json")
  kind=$(jq -r '.kind | ascii_downcase' <<<"$item")
  name=$(jq -r '.metadata.name' <<<"$item")
  jq . <<<"$item" > "$tmp/$kind-$name.json"
  files+=("$kind-$name.json")
done

# Replace the previous export wholesale, so a policy deleted on the build
# engine is pruned from the read engine.
rm -f "$out"/*.json
cp "$tmp"/configmap-roots.json "$out"/
for f in "${files[@]:1}"; do cp "$tmp/$f" "$out/"; done

{
  echo "# Generated by hack/export-trust.sh. Do not edit by hand."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "commonAnnotations:"
  echo "  argocd.argoproj.io/sync-wave: \"1\""
  echo "  argocd.argoproj.io/sync-options: SkipDryRunOnMissingResource=true"
  echo "resources:"
  for f in "${files[@]}"; do echo "- $f"; done
} > "$out/kustomization.yaml"

# Fingerprints in the form SupplyChainPolicy status.trustAnchors reports them
# (sha256 of the first PEM block's DER), to compare with
# `kubectl get scp -o jsonpath='{.items[*].status.trustAnchors}'`.
fingerprint() {
  awk '/-----BEGIN/{f=1; next} /-----END/{exit} f' | base64 -d | sha256sum | cut -d' ' -f1
}
echo "exported ${#files[@]} objects to ${out#"$root"/}"
for key in fulcio-root.pem rekor.pub ctfe.pub; do
  printf '  %-16s sha256:%s\n' "$key" \
    "$(jq -r --arg k "$key" '.data[$k] // ""' "$out/configmap-roots.json" | fingerprint)"
done
